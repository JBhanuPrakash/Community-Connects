from io import BytesIO

import qrcode
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas


def generate_qr_image(ticket_code):
    qr_data = f"COMMUNITYCONNECT-TICKET:{ticket_code}"

    qr = qrcode.QRCode(
        version=1,
        box_size=10,
        border=4,
    )

    qr.add_data(qr_data)
    qr.make(fit=True)

    image = qr.make_image(
        fill_color="black",
        back_color="white",
    )

    image_buffer = BytesIO()
    image.save(image_buffer, format="PNG")
    image_buffer.seek(0)

    return image_buffer


def generate_ticket_pdf(registration):
    event = registration.event
    user = registration.user

    buffer = BytesIO()

    pdf = canvas.Canvas(
        buffer,
        pagesize=A4,
    )

    page_width, page_height = A4

    # Header
    pdf.setFillColor(colors.HexColor("#4338CA"))
    pdf.rect(
        0,
        page_height - 110,
        page_width,
        110,
        fill=True,
        stroke=False,
    )

    pdf.setFillColor(colors.white)
    pdf.setFont("Helvetica-Bold", 24)
    pdf.drawString(
        45,
        page_height - 60,
        "CommunityConnect",
    )

    pdf.setFont("Helvetica", 12)
    pdf.drawString(
        45,
        page_height - 82,
        "Official Event Ticket",
    )

    # Ticket title
    pdf.setFillColor(colors.black)
    pdf.setFont("Helvetica-Bold", 20)
    pdf.drawString(
        45,
        page_height - 155,
        event.title[:45],
    )

    attendee_name = user.get_full_name() or user.username

    details = [
        ("Attendee", attendee_name),
        ("Username", user.username),
        ("Ticket Code", str(registration.ticket_code)),
        ("Registration Status", registration.status),
        (
            "Event Date",
            event.start_datetime.strftime(
                "%d %B %Y, %I:%M %p"
            ),
        ),
        (
            "Event Mode",
            event.get_mode_display(),
        ),
        (
            "Venue",
            event.venue_name or "Online Event",
        ),
        (
            "City",
            event.city or "Online",
        ),
    ]

    y_position = page_height - 205

    for label, value in details:
        pdf.setFont("Helvetica-Bold", 11)
        pdf.drawString(
            45,
            y_position,
            f"{label}:",
        )

        pdf.setFont("Helvetica", 11)
        pdf.drawString(
            165,
            y_position,
            str(value)[:60],
        )

        y_position -= 30

    # QR code
    qr_buffer = generate_qr_image(
        registration.ticket_code
    )

    qr_image = ImageReader(qr_buffer)

    pdf.drawImage(
        qr_image,
        page_width - 205,
        page_height - 430,
        width=150,
        height=150,
        preserveAspectRatio=True,
        mask="auto",
    )

    pdf.setFont("Helvetica", 9)
    pdf.drawCentredString(
        page_width - 130,
        page_height - 445,
        "Scan for ticket verification",
    )

    # Information box
    pdf.setFillColor(colors.HexColor("#EEF2FF"))
    pdf.roundRect(
        45,
        95,
        page_width - 90,
        90,
        8,
        fill=True,
        stroke=False,
    )

    pdf.setFillColor(colors.HexColor("#312E81"))
    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawString(
        60,
        155,
        "Important Information",
    )

    pdf.setFont("Helvetica", 9)
    pdf.drawString(
        60,
        135,
        "Carry this ticket digitally or as a printed copy.",
    )

    pdf.drawString(
        60,
        118,
        "A cancelled registration does not provide valid entry.",
    )

    pdf.setFillColor(colors.grey)
    pdf.setFont("Helvetica", 8)
    pdf.drawCentredString(
        page_width / 2,
        55,
        "Generated by CommunityConnect",
    )

    pdf.showPage()
    pdf.save()

    buffer.seek(0)

    return buffer